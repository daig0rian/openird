# OpenIRD のドライバをカーネルツリーに重ねる（組み込みでビルドするため）。
#   使い方: scripts/kernel-overlay.sh <BOARD> <KSRC>
#
# build.env の KERNEL_DRIVER_DIRS に並んだディレクトリ（各パッケージの src/）の中身を
# <KSRC>/drivers/ird/ に写し、それぞれの Kconfig / Makefile の断片をつないで
# drivers/ird/Kconfig と drivers/ird/Makefile を作り、drivers/Kconfig・drivers/Makefile
# から引く。何度呼んでも同じ結果になる。KERNEL_DRIVER_DIRS が無い機種では何もしない。
set -eu

BOARD="${1:-}"; KSRC="${2:-}"
[ -n "$BOARD" ] && [ -f "$KSRC/Makefile" ] || { echo "usage: $0 <BOARD> <KSRC>"; exit 1; }
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
matches=( "$ROOT"/br-ext-chip-*/configs/"$BOARD"_defconfig )
[ -e "${matches[0]}" ] || { echo "✗ 未知の BOARD: $BOARD"; exit 1; }
VT="$(dirname "$(dirname "${matches[0]}")")"
# shellcheck disable=SC1090,SC1091
. "$VT/board/${BOARD%%_*}/kernel/build.env"
[ -n "${KERNEL_DRIVER_DIRS:-}" ] || exit 0

D="$KSRC/drivers/ird"
rm -rf "$D"; mkdir -p "$D"
{
  echo '# Generated by scripts/kernel-overlay.sh -- edit the packages'"'"' src/Kconfig instead.'
  echo 'menu "OpenIRD drivers"'
  echo
} > "$D/Kconfig"
echo '# Generated by scripts/kernel-overlay.sh -- edit the packages'"'"' src/Makefile instead.' > "$D/Makefile"
for d in $KERNEL_DRIVER_DIRS; do
  [ -d "$ROOT/$d" ] || { echo "✗ KERNEL_DRIVER_DIRS: $d が無い"; exit 1; }
  for f in "$ROOT/$d"/*.c "$ROOT/$d"/*.h; do
    [ -e "$f" ] || continue
    [ ! -e "$D/$(basename "$f")" ] || { echo "✗ 同名のファイル: $(basename "$f")"; exit 1; }
    cp "$f" "$D/"
  done
  { cat "$ROOT/$d/Kconfig"; echo; } >> "$D/Kconfig"
  cat "$ROOT/$d/Makefile" >> "$D/Makefile"
done
echo 'endmenu' >> "$D/Kconfig"

grep -q 'drivers/ird/Kconfig' "$KSRC/drivers/Kconfig" ||
  sed -i 's|^endmenu$|source "drivers/ird/Kconfig"\n\nendmenu|' "$KSRC/drivers/Kconfig"
grep -q '+= ird/' "$KSRC/drivers/Makefile" ||
  echo 'obj-y				+= ird/' >> "$KSRC/drivers/Makefile"
echo "  drivers/ird: $(ls "$D" | wc -l) files from $(echo $KERNEL_DRIVER_DIRS | wc -w) packages"
