# wrip-fe.sh - bring up and tune the SB-TV06-WRIP front end (TC90532 + MxL601RF
# + TDA8263HN) over the GPL I2C adapter, with no vendor module in the path.
#
# Stage-C rig prototype, not part of any distributed image; the product driver
# is ird-tuner-*.  Written from docs/specs/sb-tv06-wrip-frontend.md (the section
# numbers below refer to it) and the mainline tc90522.c / tda826x.c semantics it
# cites.  Nothing here comes from the vendor's modules.
#
#   wrip-fe.sh init         once after power-on                      (section 2)
#   wrip-fe.sh t <MHz>      terrestrial tune, e.g. 557               (sections 3, 4)
#   wrip-fe.sh s <MHz>      satellite tune by IF, e.g. 1318          (sections 3, 5)
#   wrip-fe.sh status t|s   lock, raw C/N and AGC                    (section 6)
#   wrip-fe.sh sleep        standby                                  (section 3)
#
# Needs an i2c tool with "w <addr> <byte>..." and "r <addr> <reg> <n>" on
# /dev/i2c-1 (tools/yb1-i2c).  Messages on the device are ASCII only.

I=${WRIP_I2C:-/opt/openird/yb1-i2c}
T=0x10		# TC90532, terrestrial (OFDM) side
S=0x11		# TC90532, satellite (PSK) side

w() {
	$I 1 w "$@" >/dev/null || echo "i2c write failed: $*"
}
rd() {		# rd <addr> <reg> [n] -> the bytes, as "aa bb .."
	$I 1 r "$1" "$2" "${3:-1}" | sed -n 's/.* = *\(.*\)$/\1/p'
}
rmw() {		# rmw <addr> <reg> <and> <or>: read, modify, write back
	v=$(rd "$1" "$2")
	[ -n "$v" ] || { echo "i2c read failed: $1 $2"; return 1; }
	w "$1" "$2" $(( (0x$v & $3) | $4 ))
}
gt() { w $T 0xfe 0xc0 "$@"; }	# MxL601 behind the terrestrial gate (section 1)
gs() { w $S 0xfe 0xc0 "$@"; }	# TDA8263 behind the satellite gate

pairs() {	# pairs <addr> "reg val" ...: one register per message
	a=$1; shift
	for p in "$@"; do w "$a" $p; done
}

do_init() {	# section 2
	pairs $S "0x04 0x02" "0x1c 0x2a" "0x1d 0xaa" "0x1e 0x20" "0x1f 0x08" \
		 "0x85 0x7a" "0x87 0x00" "0xa3 0x55" "0xa5 0x40"
	pairs $T "0x0e 0x01" "0x0f 0x00" "0x1c 0x20" "0x1d 0x02" "0x1e 0xaa" \
		 "0x1f 0xaa" "0x31 0x0d" "0x32 0x21" "0x58 0x08" "0x75 0x02" \
		 "0x77 0x01" "0xe4 0xf4"
	gt 0xff
	gt 0x00 0x01 0x96 0x00 0x00 0x00 0x14 0x13 0x6d 0x8a
	gt 0x6d 0x0a 0xdf 0x19 0x45 0x1b 0xa9 0x59 0xaa 0x6a
	gt 0xbe 0x4c 0xcf 0x25 0xd0 0x34 0x77 0xe7 0x78 0xe3
	gt 0x6f 0x51 0x7b 0x84 0x7c 0x9f 0x56 0x41 0xcd 0x64
	gt 0xc3 0x2c 0x9d 0x61 0xf7 0x52 0x58 0x81 0xb1 0x30
	gt 0x01 0x89
	gt 0x02 0x00
	gt 0x04 0x01 0x05 0x1b
	gt 0x08 0x05 0x09 0x42 0x5e 0x00
	gt 0x0a 0x00
	gt 0x0c 0x00 0x13 0x04 0x53 0xfe 0x57 0x91 0x5d 0x0e
	gt 0x94 0x44 0x5a 0xd9 0x5b 0x16 0x5c 0xb1 0x62 0xc2
	gt 0x6e 0x01 0x6f 0x51 0x87 0x77 0x88 0x55 0x93 0x22
	gt 0x97 0x02 0xba 0x30 0x98 0xaf 0x9b 0x20 0x9c 0x1e
	gt 0xa0 0x18 0xa5 0x09 0xc2 0xa9 0xc5 0x7c 0xcd 0xe8
	gt 0xce 0x7f 0xd5 0x03 0xd9 0x04 0xea 0x0d 0xdc 0x1c
	gt 0x03 0x00 0x03 0x01
	usleep 100000
	gs 0x60 0x08
	usleep 16000
	gs 0x60 0x00
	usleep 250000
	rmw $T 0x1c 0xff 0x10
	echo "init done"
}

do_sleep() {	# section 3
	gt 0x12 0x00
	gt 0x0b 0x00
	rmw $S 0x13 0xff 0x80
	rmw $S 0x1e 0xff 0x08
	w $S 0x17 0x01
	w $T 0x03 0x80
	w $T 0x03 0x90
	rmw $T 0x1c 0xff 0x80
}

to_terr() {	# section 3: satellite side off, terrestrial side awake
	rmw $S 0x13 0xff 0x80
	rmw $S 0x1e 0xff 0x08
	w $S 0x17 0x01
	rmw $T 0x03 0xef 0x00
	rmw $T 0x1c 0x7f 0x00
	w $T 0x0e 0x01
	w $S 0x07 0x07
}

to_sat() {	# section 3: terrestrial side asleep, satellite side awake
	gs 0x60 0x08
	usleep 16000
	gs 0x60 0x00
	gt 0x12 0x00
	gt 0x0b 0x00
	w $T 0x03 0x80
	w $T 0x03 0x90
	rmw $T 0x1c 0xff 0x80
	w $S 0x17 0x00
	rmw $S 0x13 0x7f 0x00
	rmw $S 0x1e 0xf7 0x00
	w $T 0x0e 0x07
	w $S 0x07 0x01
}

tune_t() {	# section 4
	f=$1
	to_terr
	rmw $T 0x47 0x7f 0x00
	rmw $T 0x47 0x7f 0x80
	w $T 0x25 0x00
	w $T 0x20 0x00
	rmw $T 0x23 0xfe 0x01		# IF AGC manual
	word=$(( (2 * (448 * f + 64) + 7) / 14 ))	# round(64 * (f + 1/7))
	if [ "$f" -le 695 ]; then x=0x81; y=0x1f; else x=0x91; y=0x9f; fi
	gt 0x0b 0x01
	gt 0x12 0x01
	usleep 36000
	gt 0x0f 0x20
	gt 0x10 $((word & 255)) 0x11 $((word >> 8))
	gt 0x00 0x01 0x31 $x 0x00 0x00 0x7c $y
	gt 0x12 0x00 0x14 0x13 0x13 0x04
	gt 0x12 0x01
	usleep 36000
	rmw $T 0x23 0xfe 0x00		# IF AGC automatic
	w $T 0x01 0x40			# demodulator reset
}

sat_nn() {	# section 5: TDA8263 register 1 by IF frequency; register 7 by band
	r7=0x82
	case $1 in
	1049|1087) nn=0x23 ;; 1126|1164) nn=0x24 ;; 1202) nn=0x25 ;;
	1241) nn=0x26 ;; 1279|1318) nn=0x27 ;; 1356) nn=0x28 ;;
	1394) nn=0x29 ;; 1433) nn=0x2a ;; 1471) nn=0x2b ;;
	1613|1653) nn=0x2e; r7=0x81 ;; 1693|1733) nn=0x2f; r7=0x81 ;;
	1773) nn=0x30; r7=0x81 ;; 1813) nn=0x31; r7=0x81 ;;
	1853|1893) nn=0x32; r7=0x81 ;; 1933|1973) nn=0x33; r7=0x81 ;;
	2013|2053) nn=0x34; r7=0x81 ;;
	*) nn= ;;
	esac
}

tune_s() {	# section 5
	f=$1
	sat_nn "$f"
	[ -n "$nn" ] || { echo "no tuner value for IF $f"; return 1; }
	to_sat
	w $S 0x0a 0x00			# IF AGC manual
	w $S 0x11 0x00
	rmw $S 0x10 0xfd 0x00
	w $S 0x03 0x01
	gs 0x00 0x01
	gs 0x10 $nn
	gs 0x20 $((f >> 7))
	gs 0x30 $(( (f << 1) & 255 ))
	gs 0x40 0x88
	gs 0x50 0xf0
	gs 0x60 0x83
	gs 0x70 $r7
	gs 0x80 0x1a
	gs 0x90 0xd0
	gs 0x50 0xf0
	w $S 0x0a 0xff			# IF AGC automatic
	w $S 0x11 0x00
	rmw $S 0x10 0xfd 0x02
	w $S 0x03 0x01			# demodulator reset
}

do_status() {	# section 6: raw values; the C/N polynomial is left to the caller
	if [ "$1" = s ]; then
		echo "sat  c3=$(rd $S 0xc3) c5=$(rd $S 0xc5) cn_raw=$(rd $S 0xbc 2) agc=$(rd $S 0xba)"
	else
		echo "terr 80=$(rd $T 0x80) 96=$(rd $T 0x96) cn_raw=$(rd $T 0x8b 3) agc=$(rd $T 0x82 2)"
	fi
}

case "$1" in
init)	do_init ;;
t)	tune_t "$2"; sleep 1; do_status t ;;
s)	tune_s "$2"; sleep 1; do_status s ;;
status)	do_status "$2" ;;
sleep)	do_sleep ;;
*)	echo "usage: wrip-fe.sh init | t <MHz> | s <IF MHz> | status t|s | sleep" ;;
esac
